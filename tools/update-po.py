HEADER = """\
# Host Updater translation template.
# Generated by tools/update-po.py; do not edit by hand.
msgid ""
msgstr ""
"Project-Id-Version: hostupdater\\n"
"Report-Msgid-Bugs-To: \\n"
"POT-Creation-Date: 2026-10-20 00:00+0000\\n"
"PO-Revision-Date: {revision}\\n"
"Last-Translator: Gxxkx <anjiejayjo@gmail.com>\\n"
"Language: {language}\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"Plural-Forms: nplurals=1; plural=0;\\n"
"""


def esc(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def main():
    lines = VIEW.read_text(encoding="utf-8").splitlines()
    entries = []
    seen = set()
    for number, line in enumerate(lines, 1):
        for text in re.findall(r"<%:([^%]*)%>", line):
            if text not in seen:
                seen.add(text)
                entries.append((text, number))

    missing = [text for text, _ in entries if text not in TRANSLATIONS]
    if missing:
        for text in missing:
            print("missing translation: %r" % text, file=sys.stderr)
        return 1

    pot = [HEADER.format(revision="YEAR-MO-DA HO:MI+ZONE", language="")]
    pot.append("")
    for text, number in entries:
        pot.append("#: luasrc/luci/view/admin/services/hostupdater.htm:%d" % number)
        pot.append('msgid "%s"' % esc(text))
        pot.append('msgstr ""')
        pot.append("")

    po = [HEADER.format(revision="2026-10-20 00:00+0000", language="zh_CN")]
    po.append("")
    for text, number in entries:
        po.append("#: luasrc/luci/view/admin/services/hostupdater.htm:%d" % number)
        po.append('msgid "%s"' % esc(text))
        po.append('msgstr "%s"' % esc(TRANSLATIONS[text]))
        po.append("")

    POT.parent.mkdir(parents=True, exist_ok=True)
    PO.parent.mkdir(parents=True, exist_ok=True)
    POT.write_text("\n".join(pot), encoding="utf-8", newline="\n")
    PO.write_text("\n".join(po), encoding="utf-8", newline="\n")
    print("wrote %d strings" % len(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
